import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { ROUTES, JOURNEYS } from "../routes-data.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const variants = JSON.parse(readFileSync(resolve(root, "assets/image-variants.json"), "utf8"));
const output = resolve(root, "assets/runtime");
mkdirSync(output, { recursive: true });
const preview = (image) => variants[image]?.preview?.image || image;

function decoratePhotos(value) {
  if (Array.isArray(value)) return value.map(decoratePhotos);
  if (!value || typeof value !== "object") return value;
  const result = Object.fromEntries(Object.entries(value).map(([key, item]) => [key, decoratePhotos(item)]));
  if (variants[value.image]?.preview) {
    result.displayImage = variants[value.image].preview.image;
    result.thumbnailImage = variants[value.image].thumbnail.image;
  }
  return result;
}

const feed = [], timelines = {}, modules = [];
const assets = new Set();
function collectAssets(value) {
  if (typeof value === "string" && /^\.\/assets\/.+\.(?:png|webp|jpe?g|svg|gif|avif)$/i.test(value)) assets.add(value);
  else if (Array.isArray(value)) value.forEach(collectAssets);
  else if (value && typeof value === "object") Object.values(value).forEach(collectAssets);
}
for (const original of ROUTES) {
  const route = structuredClone(original);
  const image = route.storyArtwork?.image || route.image;
  const images = variants[image];
  if (!images?.card || !images?.map) throw new Error(`Missing map variants for ${route.id}`);
  const cardArtwork = {
    ...images.card,
    smallImage: images.cardSmall.image,
    smallWidth: images.cardSmall.width,
    smallHeight: images.cardSmall.height
  };
  if (route.storyArtwork) {
    route.storyArtwork.image = images.map.image;
    route.storyArtwork.previewImage = images.card.image;
  }
  route.cardArtwork = cardArtwork;
  const journey = decoratePhotos(JOURNEYS[route.id]);
  journey.previewImages = (journey.previewImages || []).map(preview);
  const payload = JSON.stringify({ route, journey });
  collectAssets({ route, journey });
  const hash = createHash("sha256").update(payload).digest("hex").slice(0, 12);
  const name = `${route.id}-${hash}.js`;
  writeFileSync(resolve(output, name), `export default ${payload};\n`);
  modules.push([route.id, `./assets/runtime/${name}`]);

  const { id, city, region, place, flag, title, days, tags, theme, accent, intro } = route;
  feed.push({ id, city, region, place, flag, title, days, tags, theme, accent, intro, image: cardArtwork.image, cardArtwork,
    map: { points: route.map.points.map(({ name, color }) => ({ name, color })) },
    story: route.story.map(({ title, time }) => ({ title, time })) });
  timelines[id] = { stopTimes: journey.stopTimes };
}

const source = `// Generated by scripts/build-runtime-data.mjs; route details load only on navigation.\n`
  + `export const ROUTES=${JSON.stringify(feed)};\n`
  + `export const JOURNEYS=${JSON.stringify(timelines)};\n`
  + `export const ROUTE_LOADERS={${modules.map(([id, path]) => `${JSON.stringify(id)}:()=>import(${JSON.stringify(path)})`).join(",")}};\n`;
writeFileSync(resolve(root, "feed-data.js"), source);
writeFileSync(resolve(output, "runtime-assets.json"), JSON.stringify([...assets].sort(), null, 2) + "\n");
console.log(`Generated ${feed.length} lazy route modules; feed directory ${(Buffer.byteLength(source) / 1024).toFixed(1)} KiB.`);
